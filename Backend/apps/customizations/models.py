
from django.conf import settings
from django.core.validators import FileExtensionValidator
from django.db import models


class ProductCustomization(models.Model):

    class CustomizationStatus(models.TextChoices):
        DRAFT = "draft", "Draft"
        SUBMITTED = "submitted", "Submitted"

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="product_customizations"
    )

    product = models.ForeignKey(
        "products.Product",
        on_delete=models.PROTECT,
        related_name="customizations"
    )

    customization_name = models.CharField(
        max_length=255,
        blank=True
    )

    # Stores the editor configuration:
    # text, font, color, position, rotation, logo settings, etc.
    design_data = models.JSONField(default=dict, blank=True)

    # Uploaded customer logo
    logo_file = models.FileField(
        upload_to="customizations/logos/",
        blank=True,
        null=True,
        validators=[
            FileExtensionValidator(
                allowed_extensions=["png", "jpg", "jpeg", "svg"]
            )
        ]
    )

    # Preview generated by the frontend editor
    preview_image = models.ImageField(
        upload_to="customizations/previews/",
        blank=True,
        null=True
    )

    # Vector output generated by the frontend/editor workflow
    svg_file = models.FileField(
        upload_to="customizations/exports/svg/",
        blank=True,
        null=True,
        validators=[
            FileExtensionValidator(
                allowed_extensions=["svg"]
            )
        ]
    )

    pdf_file = models.FileField(
        upload_to="customizations/exports/pdf/",
        blank=True,
        null=True,
        validators=[
            FileExtensionValidator(
                allowed_extensions=["pdf"]
            )
        ]
    )

    status = models.CharField(
        max_length=20,
        choices=CustomizationStatus.choices,
        default=CustomizationStatus.DRAFT
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "product_customizations"
        ordering = ["-created_at"]

    def __str__(self):
        return (
            f"{self.customization_name or self.product.product_name} "
            f"- {self.user}"
        )
